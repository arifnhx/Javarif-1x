// Builds geo.js (country outlines for the engine) from world-atlas, and
// checks that every route and swarm path in scene.js stays at sea.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import './paths.js';
import './scene.js';

const { SCENE, PATHS } = globalThis;
const load = (f) => {
  const topo = JSON.parse(readFileSync(new URL(`node_modules/world-atlas/${f}`, import.meta.url)));
  return feature(topo, topo.objects.countries).features;
};
const hi = load('countries-10m.json');
const lo = load('countries-50m.json');

function pack(features, [w, s, e, n], digits) {
  const q = 10 ** digits;
  const out = [];
  for (const f of features) {
    if (!f.geometry) continue;
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    const rings = [];
    for (const poly of polys) {
      for (const ring of poly) {
        if (!ring.some(([x, y]) => x >= w && x <= e && y >= s && y <= n)) continue;
        const flat = [];
        let px = NaN, py = NaN;
        for (const [x, y] of ring) {
          const rx = Math.round(x * q) / q, ry = Math.round(y * q) / q;
          if (rx === px && ry === py) continue;
          flat.push(rx, ry); px = rx; py = ry;
        }
        if (flat.length >= 6) rings.push(flat);
      }
    }
    if (rings.length) out.push({ id: +f.id, name: f.properties.name, rings });
  }
  return out;
}

const GEO = {
  // Close-ups (Gulf, strait, Gulf of Oman) use 1:10m; wide views 1:50m.
  hi: { bbox: [42, 20, 64, 33], features: pack(hi, [42, 20, 64, 33], 3) },
  lo: { bbox: [10, -25, 170, 62], features: pack(lo, [10, -25, 170, 62], 2) },
};
writeFileSync(new URL('geo.js', import.meta.url),
  '// Generated by build-geo.mjs from world-atlas (Natural Earth, public domain). Do not edit.\n' +
  `window.GEO=${JSON.stringify(GEO)};\n`);
console.log('geo.js written:', GEO.hi.features.length, 'hi /', GEO.lo.features.length, 'lo features');

// --- Sea check -------------------------------------------------------------
// Planar even-odd test on the packed rings: the same geometry the engine fills.
const inRing = (r, x, y) => {
  let c = false;
  for (let i = 0, j = r.length - 2; i < r.length; j = i, i += 2) {
    if ((r[i + 1] > y) !== (r[j + 1] > y) && x < ((r[j] - r[i]) * (y - r[i + 1])) / (r[j + 1] - r[i + 1]) + r[i]) c = !c;
  }
  return c;
};
const inHi = ([x, y]) => x >= 42 && x <= 64 && y >= 20 && y <= 33;
const onLand = ([x, y]) => (inHi([x, y]) ? GEO.hi : GEO.lo).features.some((f) =>
  f.rings.reduce((c, r) => (inRing(r, x, y) ? !c : c), false));
const checks = [
  ...SCENE.routes.map((r) => [`route ${r.id}`, PATHS.smooth(r.pts), 0.03]),
  ...SCENE.swarms.filter((s) => s.pts).map((s, i) => [`swarm column ${i}`, PATHS.smooth(s.pts), 0]),
  ...SCENE.swarms.filter((s) => s.loop).map((s, i) => [`swarm loop ${i}`, PATHS.ellipse(s.loop), 0]),
];
let bad = 0;
for (const [name, path, trim] of checks) {
  const hits = [];
  for (let i = 0; i <= 200; i++) {
    const f = i / 200;
    if (f < trim || f > 1 - trim) continue;
    const p = PATHS.at(path, f * path.length);
    const ll = PATHS.unmerc([p.x, p.y]);
    if (onLand(ll)) hits.push(ll.map((v) => v.toFixed(2)).join(','));
  }
  if (hits.length) { bad++; console.log(`LAND ${name}: ${hits.length} samples, e.g. ${hits.slice(0, 4).join(' | ')}`); }
}
for (const fl of [SCENE.narrows.a, SCENE.narrows.b]) console.log('narrows end', fl, onLand(fl) ? 'land' : 'sea');
console.log(bad ? `${bad} path(s) cross land` : 'all paths at sea');
process.exitCode = bad ? 1 : 0;
